<?php

namespace App\Services;

use App\Models\CardTemplate;
use App\Models\UserCardTemplate;

/**
 * The canonical server-side template catalog + apply pipeline.
 *
 * ONE apply contract for EVERY template kind (the frontend gallery is UX
 * only — no entitlement can be bypassed through the UI):
 *
 *   authorize → deserialize → clone (NEW layer ids) → placeholder fill
 *     → consumer entitlement limits → document
 *
 * Sources (TemplateSource implementations):
 *   builtin — api/resources/card-templates/builtin-catalog.json, generated
 *             from the frontend templatesCatalog.ts (single authoring home).
 *   db      — card_templates rows (admin-created / designer-submitted).
 *   personal— user_card_templates rows (private, owner-only).
 *
 * Layer ids are ALWAYS regenerated on apply: no id may ever be shared
 * between a template and a user document (immutability contract).
 */
class TemplateService
{
    /** Builtin catalog file (generated by web's export script). */
    public const BUILTIN_CATALOG = 'card-templates/builtin-catalog.json';

    /** Placeholder tokens templates may use; filled from the business/user. */
    private const PLACEHOLDERS = ['name', 'category', 'phone', 'website', 'address', 'slug'];

    // ------------------------------------------------------------------
    // Listing (gallery)
    // ------------------------------------------------------------------

    /**
     * The gallery payload: builtin catalog + approved DB templates, each
     * with a UX-only `entitled` flag. Background is EXTRACTED from
     * design_json — never a second source of truth.
     *
     * @return array<int, array<string, mixed>>
     */
    public function gallery(?callable $isEntitledBuiltin, ?callable $isEntitledDb): array
    {
        $items = [];

        foreach ($this->builtinCatalog() as $entry) {
            $items[] = [
                'id' => (string) $entry['id'],
                'source' => 'builtin',
                'name_fa' => (string) $entry['name'],
                'category' => (string) ($entry['category'] ?? 'general'),
                'description' => (string) ($entry['description'] ?? ''),
                'background' => (string) ($entry['background'] ?? ''),
                'entitled' => $isEntitledBuiltin ? (bool) $isEntitledBuiltin((string) $entry['id']) : true,
            ];
        }

        foreach (CardTemplate::query()->approved()->orderBy('sort_order')->orderBy('id')->get() as $template) {
            $items[] = [
                'id' => (string) $template->slug,
                'db_id' => $template->id,
                'source' => 'db',
                'origin' => $template->origin,
                'name_fa' => $template->name_fa,
                'category' => $template->category,
                'background' => (string) $template->background(),
                'entitled' => $isEntitledDb ? (bool) $isEntitledDb($template) : true,
            ];
        }

        // Legacy constrained-editor template KEYS (cards.template on the five
        // factory identities) surface as builtin rows so the gallery covers
        // every grantable value of card_templates in one list.
        $seen = array_flip(array_column($items, 'id'));
        foreach (['classic', 'midnight', 'emerald', 'local', 'creative'] as $legacyKey) {
            if (isset($seen[$legacyKey])) {
                continue;
            }
            $items[] = [
                'id' => $legacyKey,
                'source' => 'builtin',
                'name_fa' => 'قالب کلاسیک ' . $legacyKey,
                'category' => 'general',
                'description' => 'قالب پایه کارت‌ساز کلاسیک.',
                'background' => '#f6f8fb',
                'entitled' => $isEntitledBuiltin ? (bool) $isEntitledBuiltin($legacyKey) : true,
            ];
        }

        ksort($items);

        return $items;
    }

    // ------------------------------------------------------------------
    // Apply pipeline
    // ------------------------------------------------------------------

    /**
     * Build a fresh user document from a builtin template (already
     * authorized by the controller).
     *
     * @return array{background: string, layers: list<array<string, mixed>>}
     */
    public function applyBuiltin(string $templateId, array $fills): array
    {
        foreach ($this->builtinCatalog() as $entry) {
            if ((string) $entry['id'] === $templateId) {
                return $this->materialize(
                    is_array($entry['document'] ?? null) ? $entry['document'] : [],
                    $fills
                );
            }
        }

        abort(404, 'قالب یافت نشد.');
    }

    /**
     * Build a fresh user document from a DB template (already authorized).
     *
     * @return array{background: string, layers: list<array<string, mixed>>}
     */
    public function applyDb(CardTemplate $template, array $fills): array
    {
        $doc = $template->document();
        if ($doc === null) {
            abort(422, 'سند قالب نامعتبر است.');
        }

        return $this->materialize($doc, $fills);
    }

    /**
     * Build a fresh user document from a PRIVATE user template.
     *
     * @return array{background: string, layers: list<array<string, mixed>>}
     */
    public function applyPersonal(UserCardTemplate $template, array $fills): array
    {
        $doc = $template->document();
        if ($doc === null) {
            abort(422, 'سند قالب نامعتبر است.');
        }

        return $this->materialize($doc, $fills);
    }

    /**
     * Clone + regenerate ids + fill placeholders. The heart of the apply
     * contract: the stored template is NEVER handed to a user document
     * un-cloned, and no layer id survives from template to document.
     *
     * @return array{background: string, layers: list<array<string, mixed>>}
     */
    private function materialize(array $doc, array $fills): array
    {
        $background = is_string($doc['background'] ?? null) ? $doc['background'] : null;
        if ($background === null) {
            abort(422, 'سند قالب نامعتبر است.');
        }

        $layers = [];
        foreach ($doc['layers'] ?? [] as $layer) {
            if (! is_array($layer)) {
                continue;
            }
            $layer = $this->fillPlaceholders($layer, $fills);
            // Fresh unique id for EVERY layer — the clone contract.
            $layer['id'] = 'layer-' . bin2hex(random_bytes(8));
            $layers[] = $layer;
        }

        return ['background' => $background, 'layers' => $layers];
    }

    /** Replace {{token}} placeholders inside every scalar string field. */
    private function fillPlaceholders(array $layer, array $fills): array
    {
        array_walk_recursive($layer, function (&$value) use ($fills): void {
            if (! is_string($value) || ! str_contains($value, '{{')) {
                return;
            }
            foreach (self::PLACEHOLDERS as $token) {
                $value = str_replace(
                    '{{' . $token . '}}',
                    (string) ($fills[$token] ?? ''),
                    $value
                );
            }
        });

        return $layer;
    }

    // ------------------------------------------------------------------
    // Builtin catalog
    // ------------------------------------------------------------------

    /**
     * The generated builtin catalog (canonical server-side twin of the TS
     * catalog). Missing file = deployment error: the templates:import
     * command publishes it from web's export script.
     *
     * @return list<array<string, mixed>>
     */
    public function builtinCatalog(): array
    {
        $path = resource_path(self::BUILTIN_CATALOG);
        if (! is_file($path)) {
            return [];
        }

        $decoded = json_decode((string) file_get_contents($path), true);

        return is_array($decoded['templates'] ?? null) ? $decoded['templates'] : [];
    }

    /** All builtin ids — the universe for knownValues('card_templates'). */
    public function builtinIds(): array
    {
        return array_map(
            static fn (array $entry): string => (string) $entry['id'],
            $this->builtinCatalog()
        );
    }
}
